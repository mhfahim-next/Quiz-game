/**
 * Generates supabase/seed.sql from scripts/seed-data.ts
 * Used by `supabase db reset` (and can be pasted into the SQL editor).
 * Run: npm run seed:sql
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { seedCategories, seedId } from "./seed-data";

const esc = (s: string) => `'${s.replace(/'/g, "''")}'`;
const out: string[] = ["-- GENERATED by scripts/generate-seed-sql.ts — do not edit by hand.", "-- Idempotent: safe to run more than once.", ""];

for (const c of seedCategories) {
  const cid = seedId("category", c.slug);
  out.push(
    `insert into public.categories (id, slug, name, description, icon, color, position, is_published) values (` +
      `${esc(cid)}, ${esc(c.slug)}, ${esc(c.name)}, ${esc(c.description)}, ${esc(c.icon)}, ${esc(c.color)}, ${c.position}, true)\n` +
      `on conflict (slug) do update set name = excluded.name, description = excluded.description, icon = excluded.icon, color = excluded.color, position = excluded.position;`,
  );
  for (const l of c.levels) {
    const lid = seedId("level", c.slug, l.position);
    out.push(
      `insert into public.levels (id, category_id, position, pass_percent, question_count, is_published) values (` +
        `${esc(lid)}, ${esc(cid)}, ${l.position}, ${l.pass_percent}, ${l.question_count}, true)\n` +
        `on conflict (id) do update set pass_percent = excluded.pass_percent, question_count = excluded.question_count, is_published = true;`,
    );
    const rows = l.questions.map((q, i) => {
      const qid = seedId("question", c.slug, l.position, i);
      return `  (${esc(qid)}, ${esc(lid)}, ${esc(q.text)}, ${esc(JSON.stringify(q.options))}::jsonb, ${q.correct_index}, ${esc(q.explanation)})`;
    });
    out.push(
      `insert into public.questions (id, level_id, text, options, correct_index, explanation) values\n${rows.join(",\n")}\n` +
        `on conflict (id) do update set text = excluded.text, options = excluded.options, correct_index = excluded.correct_index, explanation = excluded.explanation;`,
    );
  }
  out.push("");
}

const file = resolve(__dirname, "../supabase/seed.sql");
writeFileSync(file, out.join("\n") + "\n");
console.log(`wrote ${file}`);
