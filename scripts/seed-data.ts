/**
 * Seed content for Quiz Kids: 5 categories x 3 levels x 10 questions (Bangla).
 *
 * Authoring format: q(text, correctAnswer, [wrong1, wrong2, wrong3], explanation)
 * The correct answer is placed at a deterministic, varied position (see CORRECT_POSITIONS)
 * so the right answer is not always the first button.
 */

export type SeedQuestion = {
  text: string;
  options: [string, string, string, string];
  correct_index: number;
  explanation: string;
};
export type SeedLevel = { position: number; pass_percent: number; question_count: number; questions: SeedQuestion[] };
export type SeedCategory = {
  slug: string;
  name: string;
  description: string;
  icon: string;
  color: string;
  position: number;
  levels: SeedLevel[];
};

const CORRECT_POSITIONS = [2, 0, 3, 1, 1, 3, 0, 2, 3, 1];

function level(position: number, rows: ReturnType<typeof q>[]): SeedLevel {
  if (rows.length !== 10) throw new Error(`level ${position} must have 10 questions, got ${rows.length}`);
  const questions = rows.map((r, i) => {
    const at = CORRECT_POSITIONS[(i + position) % CORRECT_POSITIONS.length];
    const options = [...r.wrong];
    options.splice(at, 0, r.correct);
    return { text: r.text, options: options as SeedQuestion["options"], correct_index: at, explanation: r.explanation };
  });
  return { position, pass_percent: 70, question_count: 10, questions };
}

function q(text: string, correct: string, wrong: [string, string, string], explanation: string) {
  return { text, correct, wrong, explanation };
}

